def make_avatar(path):
    W, H = 512, 768
    img = Image.new("RGB", (W, H), (4, 8, 14))
    d = ImageDraw.Draw(img)
    for y in range(H):
        t = y / H
        d.line([(0, y), (W, y)], fill=(int(4 + 16 * (1 - t) ** 2),
                                       int(8 + 30 * (1 - t) ** 2),
                                       int(14 + 44 * (1 - t) ** 2)))

    cx, cy = W // 2, 300
    glow = Image.new("RGB", (W, H), (0, 0, 0))
    gd = ImageDraw.Draw(glow)
    gd.ellipse([cx - 190, cy - 190, cx + 190, cy + 190], fill=(26, 86, 132))
    gd.ellipse([cx - 110, cy - 110, cx + 110, cy + 110], fill=(42, 118, 172))
    glow = glow.filter(ImageFilter.GaussianBlur(55))
    from PIL import ImageChops
    img = ImageChops.screen(img, glow)
    d = ImageDraw.Draw(img)

    # 冰裂纹
    import random
    random.seed(7)
    for i in range(30):
        a = random.uniform(0, math.tau)
        r0 = random.uniform(24, 46)
        r1 = random.uniform(100, 210)
        x0, y0 = cx + math.cos(a) * r0, cy + math.sin(a) * r0
        x1, y1 = cx + math.cos(a) * r1, cy + math.sin(a) * r1
        mx = (x0 + x1) / 2 + random.uniform(-22, 22)
        my = (y0 + y1) / 2 + random.uniform(-22, 22)
        d.line([(x0, y0), (mx, my)], fill=(188, 224, 248), width=2)
        d.line([(mx, my), (x1, y1)], fill=(96, 156, 196), width=1)

    # 同心冰环
    for r, w, c in [(58, 2, (120, 180, 210)), (96, 1, (80, 130, 165)), (140, 1, (55, 95, 125))]:
        d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=c, width=w)

    # 中心一点余火
    ember = Image.new("RGB", (W, H), (0, 0, 0))
    ed = ImageDraw.Draw(ember)
    ed.ellipse([cx - 16, cy - 16, cx + 16, cy + 16], fill=(230, 120, 40))
    ember = ember.filter(ImageFilter.GaussianBlur(14))
    img = Image.blend(img, ember, 0.9)
    d = ImageDraw.Draw(img)
    d.ellipse([cx - 6, cy - 6, cx + 6, cy + 6], fill=(255, 214, 150))
    d.ellipse([cx - 2, cy - 2, cx + 2, cy + 2], fill=(255, 255, 240))

    f1, f2, f3 = font(76), font(22), font(17)
    t1 = "冰封求生"
    d.text(((W - d.textlength(t1, font=f1)) / 2, 492), t1, font=f1, fill=(226, 240, 248))
    t2 = "B I N G   F E N G   Q I U   S H E N G"
    d.text(((W - d.textlength(t2, font=f3)) / 2 - 6, 588), t2, font=f3, fill=(70, 110, 140))
    t3 = "AI 互动小说 · 主持人"
    d.text(((W - d.textlength(t3, font=f2)) / 2, 638), t3, font=f2, fill=(150, 175, 192))
    img.save(path, "PNG")

