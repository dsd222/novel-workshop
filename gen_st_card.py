def font(size):
    for p in [r"C:\Windows\Fonts\msyh.ttc", r"C:\Windows\Fonts\msyhbd.ttc", r"C:\Windows\Fonts\simhei.ttf"]:
        if os.path.exists(p):
            try:
                return ImageFont.truetype(p, size)
            except Exception:
                pass
    return ImageFont.load_default()

def make_avatar(path):
    W, H = 512, 768
    img = Image.new("RGB", (W, H), (6, 6, 8))
    d = ImageDraw.Draw(img)
    for y in range(H):
        t = y / H
        r = int(6 + 26 * (1 - t) ** 2)
        g = int(6 + 6 * (1 - t) ** 2)
        b = int(9 + 10 * (1 - t) ** 2)
        d.line([(0, y), (W, y)], fill=(r, g, b))

    # 眼睛光晕
    glow = Image.new("RGB", (W, H), (0, 0, 0))
    gd = ImageDraw.Draw(glow)
    cx, cy = W // 2, 300
    gd.ellipse([cx - 150, cy - 95, cx + 150, cy + 95], fill=(120, 10, 14))
    glow = glow.filter(ImageFilter.GaussianBlur(60))
    img = Image.blend(img, Image.new("RGB", (W, H), (0, 0, 0)), 0.0)
    img = Image.composite(img, img, Image.new("L", (W, H), 255))
    img = Image.blend(img, glow, 0.55)
    d = ImageDraw.Draw(img)

    # 眼白
    d.ellipse([cx - 120, cy - 62, cx + 120, cy + 62], fill=(198, 192, 182))
    # 虹膜
    d.ellipse([cx - 52, cy - 52, cx + 52, cy + 52], fill=(96, 6, 10))
    d.ellipse([cx - 46, cy - 46, cx + 46, cy + 46], fill=(150, 12, 16))
    # 竖瞳
    d.ellipse([cx - 14, cy - 48, cx + 14, cy + 48], fill=(4, 2, 3))
    # 高光
    d.ellipse([cx + 16, cy - 34, cx + 30, cy - 20], fill=(230, 220, 210))
    # 上眼睑压暗
    d.ellipse([cx - 122, cy - 96, cx + 122, cy - 8], fill=(6, 6, 8))
    d.ellipse([cx - 120, cy - 62, cx + 120, cy + 62], outline=(30, 8, 10), width=3)

    # 血丝
    for a, b in [((cx - 100, cy + 10), (cx - 40, cy + 4)), ((cx + 90, cy - 20), (cx + 45, cy - 12)),
                 ((cx - 80, cy - 30), (cx - 35, cy - 24)), ((cx + 70, cy + 35), (cx + 30, cy + 28))]:
        d.line([a, b], fill=(120, 30, 30), width=2)

    f1 = font(72)
    f2 = font(22)
    f3 = font(18)
    t1 = "神秘复苏"
    w1 = d.textlength(t1, font=f1)
    d.text(((W - w1) / 2, 500), t1, font=f1, fill=(214, 206, 196))
