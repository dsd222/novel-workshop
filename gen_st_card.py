    d.text(((W - w2) / 2, 588), t2, font=f3, fill=(120, 40, 40))
    t3 = "AI 互动小说 · 主持人"
    w3 = d.textlength(t3, font=f2)
    d.text(((W - w3) / 2, 640), t3, font=f2, fill=(150, 142, 134))

    img.save(path, "PNG")

