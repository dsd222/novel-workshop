    print("card   ->", png, os.path.getsize(png), "bytes, chara b64 len", len(b64))

    # 自检：读回 chara 块
    from PIL import Image as I2
    chk = I2.open(png)
    ok = "chara" in chk.text
    back = json.loads(base64.b64decode(chk.text["chara"]).decode("utf-8")) if ok else {}
    print("verify -> chara_chunk:", ok, "| spec:", back.get("spec"), "| name:", back.get("data", {}).get("name"))

